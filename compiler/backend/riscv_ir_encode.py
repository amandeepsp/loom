"""Encode the generated xDSL RISC-V target IR subset to RV32 machine code."""

from __future__ import annotations

from collections import Counter

from xdsl.dialects import riscv as xdsl_riscv
from xdsl.dialects import riscv_scf, rv32
from xdsl.dialects.builtin import ModuleOp
from xdsl.ir import Block, Operation, SSAValue

from compiler.dialects import loom_riscv

from . import riscv
from .rv32_builder import RV32Builder


TEMP_REGS = (
    riscv.T0,
    riscv.T1,
    riscv.T2,
    riscv.A0,
    riscv.A1,
    riscv.A2,
    riscv.A3,
    riscv.A4,
    riscv.A5,
    riscv.A6,
    riscv.A7,
    riscv.T3,
    riscv.T4,
    riscv.T5,
    riscv.T6,
    riscv.S0,
    riscv.S1,
    riscv.S2,
    riscv.S3,
    riscv.S4,
)

SAVED_REGS = (riscv.S0, riscv.S1, riscv.S2, riscv.S3, riscv.S4)


def encode_riscv_module(module: ModuleOp) -> bytes:
    """Encode a target IR module generated by ``riscv_ir.py``."""

    encoder = _RiscvModuleEncoder(module)
    return encoder.encode()


class _RiscvModuleEncoder:
    def __init__(self, module: ModuleOp):
        self.module = module
        self.builder = RV32Builder()
        self.uses = _use_counts(module)
        self.reg_by_value: dict[SSAValue, int] = {}
        self.value_by_reg: dict[int, SSAValue] = {}
        self.free_regs = list(TEMP_REGS)
        self.pinned: set[SSAValue] = set()

    def encode(self) -> bytes:
        self._emit_prologue()
        self._encode_ops(tuple(self.module.body.block.ops))
        self._emit_epilogue()
        self.builder.emit(riscv.ret())
        return self.builder.bytes()

    def _emit_prologue(self) -> None:
        frame_size = len(SAVED_REGS) * 4
        self.builder.emit(riscv.addi(riscv.SP, riscv.SP, -frame_size))
        for index, reg in enumerate(SAVED_REGS):
            self.builder.emit(riscv.sw(reg, riscv.SP, index * 4))

    def _emit_epilogue(self) -> None:
        frame_size = len(SAVED_REGS) * 4
        for index, reg in enumerate(SAVED_REGS):
            self.builder.emit(riscv.lw(reg, riscv.SP, index * 4))
        self.builder.emit(riscv.addi(riscv.SP, riscv.SP, frame_size))

    def _encode_ops(self, ops: tuple[Operation, ...]) -> None:
        for op in ops:
            self._encode_op(op)

    def _encode_op(self, op: Operation) -> None:
        match op:
            case rv32.LiOp():
                rd = self._define(op.rd)
                self.builder.li(rd, int(op.immediate.value.data))
                self._free_dead_results(op)
            case xdsl_riscv.AddOp():
                rs1 = self._use(op.rs1)
                rs2 = self._use(op.rs2)
                rd = self._define(op.rd)
                self.builder.emit(riscv.add(rd, rs1, rs2))
                self._finish_op(op)
            case xdsl_riscv.XorOp():
                rs1 = self._use(op.rs1)
                rs2 = self._use(op.rs2)
                rd = self._define(op.rd)
                self.builder.emit(riscv.xor(rd, rs1, rs2))
                self._finish_op(op)
            case xdsl_riscv.AddiOp():
                rs1 = self._use(op.rs1)
                rd = self._define(op.rd)
                self.builder.emit(riscv.addi(rd, rs1, int(op.immediate.value.data)))
                self._finish_op(op)
            case xdsl_riscv.SlliOp():
                rs1 = self._use(op.rs1)
                rd = self._define(op.rd)
                self.builder.emit(riscv.slli(rd, rs1, int(op.immediate.value.data)))
                self._finish_op(op)
            case xdsl_riscv.SrliOp():
                rs1 = self._use(op.rs1)
                rd = self._define(op.rd)
                self.builder.emit(riscv.srli(rd, rs1, int(op.immediate.value.data)))
                self._finish_op(op)
            case xdsl_riscv.SltiuOp():
                rs1 = self._use(op.rs1)
                rd = self._define(op.rd)
                self.builder.emit(riscv.sltiu(rd, rs1, int(op.immediate.value.data)))
                self._finish_op(op)
            case xdsl_riscv.LwOp():
                rs1 = self._use(op.rs1)
                rd = self._define(op.rd)
                self.builder.emit(riscv.lw(rd, rs1, int(op.immediate.value.data)))
                self._finish_op(op)
            case xdsl_riscv.SwOp():
                rs1 = self._use(op.rs1)
                rs2 = self._use(op.rs2)
                self.builder.emit(riscv.sw(rs2, rs1, int(op.immediate.value.data)))
                self._finish_op(op)
            case xdsl_riscv.SbOp():
                rs1 = self._use(op.rs1)
                rs2 = self._use(op.rs2)
                self.builder.emit(riscv.sb(rs2, rs1, int(op.immediate.value.data)))
                self._finish_op(op)
            case loom_riscv.ComputeWaitOp():
                self.builder.emit(riscv.compute_wait().encode())
                self._finish_op(op)
            case loom_riscv.WaitPreviousComputeOp():
                k_base = self._use(op.k_base)
                skip_wait = self.builder.new_label("skip_initial_compute_wait")
                self.builder.branch_label("beq", k_base, riscv.ZERO, skip_wait)
                self.builder.emit(riscv.compute_wait().encode())
                self.builder.label(skip_wait)
                self._finish_op(op)
            case loom_riscv.ComputeStartOp():
                flags = self._use(op.flags)
                k_count = self._use(op.k_count)
                self.builder.emit(
                    riscv.compute_start(flags_reg=flags, k_count_reg=k_count).encode()
                )
                self._finish_op(op)
            case loom_riscv.WriteEpilogueParamOp():
                channel = self._use(op.channel)
                value = self._use(op.value)
                self.builder.emit(
                    riscv.write_epilogue_param(
                        int(op.field.value.data),
                        channel_reg=channel,
                        value_reg=value,
                    ).encode()
                )
                self._finish_op(op)
            case loom_riscv.WriteConfigOp():
                value = self._use(op.value)
                self.builder.emit(
                    riscv.write_config(
                        int(op.register.value.data),
                        value_reg=value,
                    ).encode()
                )
                self._finish_op(op)
            case loom_riscv.ReadResultOp():
                index = self._use(op.index)
                rd = self._define(op.rd)
                self.builder.emit(riscv.read_result(rd=rd, index_reg=index).encode())
                self._finish_op(op)
            case riscv_scf.ForOp():
                self._encode_for(op)
            case riscv_scf.WhileOp():
                self._encode_while(op)
            case xdsl_riscv.CommentOp() | riscv_scf.YieldOp():
                self._finish_op(op)
            case riscv_scf.ConditionOp():
                raise TypeError("riscv_scf.condition is only supported inside while")
            case _:
                raise TypeError(f"unsupported RISC-V target IR op: {op.name}")

    def _encode_for(self, op: riscv_scf.ForOp) -> None:
        lb = self._use(op.lb)
        ub = self._use(op.ub)
        iv = self._assign_block_arg(op.body.block.args[0])
        self.builder.emit(riscv.addi(iv, lb, 0))

        check_label = self.builder.new_label("for_check")
        body_label = self.builder.new_label("for_body")
        done_label = self.builder.new_label("for_done")
        self.builder.label(check_label)
        self.builder.branch_label("blt", iv, ub, body_label)
        self.builder.j_label(done_label)
        self.builder.label(body_label)
        self._encode_ops(_body_ops_without_terminator(op.body.block))
        step = _static_step(op)
        self.builder.emit(riscv.addi(iv, iv, step))
        self.builder.j_label(check_label)
        self.builder.label(done_label)
        self._finish_op(op)
        self.pinned.discard(op.body.block.args[0])
        self._free_value(op.body.block.args[0])

    def _encode_while(self, op: riscv_scf.WhileOp) -> None:
        if op.arguments or op.results:
            raise TypeError("only argument-free riscv_scf.while is supported")
        before_ops = tuple(op.before_region.block.ops)
        if not before_ops or not isinstance(before_ops[-1], riscv_scf.ConditionOp):
            raise TypeError("riscv_scf.while before region must end in condition")
        condition = before_ops[-1]

        check_label = self.builder.new_label("while_check")
        body_label = self.builder.new_label("while_body")
        done_label = self.builder.new_label("while_done")
        self.builder.label(check_label)
        self._encode_ops(before_ops[:-1])
        cond_reg = self._use(condition.cond)
        self.builder.branch_label("bne", cond_reg, riscv.ZERO, body_label)
        self.builder.j_label(done_label)
        self.builder.label(body_label)
        self._encode_ops(_body_ops_without_terminator(op.after_region.block))
        self.builder.j_label(check_label)
        self.builder.label(done_label)
        self._finish_op(condition)
        self._finish_op(op)

    def _use(self, value: SSAValue) -> int:
        if value not in self.reg_by_value:
            self._define(value)
        return self.reg_by_value[value]

    def _define(self, value: SSAValue) -> int:
        fixed = _fixed_reg(value)
        if fixed is not None:
            self.reg_by_value[value] = fixed
            return fixed
        if value in self.reg_by_value:
            return self.reg_by_value[value]
        if not self.free_regs:
            raise RuntimeError("RISC-V target IR encoder ran out of temporary registers")
        reg = self.free_regs.pop(0)
        self.reg_by_value[value] = reg
        self.value_by_reg[reg] = value
        return reg

    def _assign_block_arg(self, value: SSAValue) -> int:
        self.pinned.add(value)
        return self._define(value)

    def _finish_op(self, op: Operation) -> None:
        for operand in op.operands:
            self.uses[operand] -= 1
            if self.uses[operand] <= 0:
                self._free_value(operand)
        self._free_dead_results(op)

    def _free_dead_results(self, op: Operation) -> None:
        for result in op.results:
            if self.uses[result] <= 0:
                self._free_value(result)

    def _free_value(self, value: SSAValue) -> None:
        if value in self.pinned:
            return
        reg = self.reg_by_value.pop(value, None)
        if reg is None or reg not in self.value_by_reg:
            return
        del self.value_by_reg[reg]
        if reg in TEMP_REGS and reg not in self.free_regs:
            self.free_regs.insert(0, reg)


def _use_counts(module: ModuleOp) -> Counter[SSAValue]:
    counts = Counter[SSAValue]()
    for op in module.walk():
        for operand in op.operands:
            counts[operand] += 1
    return counts


def _fixed_reg(value: SSAValue) -> int | None:
    typ = value.type
    if isinstance(typ, xdsl_riscv.IntRegisterType) and typ.is_allocated:
        if typ.index is None:
            return None
        return int(typ.index.data)
    return None


def _static_step(op: riscv_scf.ForOp) -> int:
    step = op.step
    if not hasattr(step, "value"):
        raise TypeError("dynamic riscv_scf.for steps are not supported")
    return int(step.value.data)


def _body_ops_without_terminator(block: Block) -> tuple[Operation, ...]:
    ops = tuple(block.ops)
    if ops and isinstance(ops[-1], riscv_scf.YieldOp):
        return ops[:-1]
    return ops
